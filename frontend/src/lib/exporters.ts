export type Row = Record<string, string | number | null | undefined>

const esc = (v: unknown) => { const s = v === null || v === undefined ? '' : String(v); return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s }
export function toCsv(rows: Row[]): string {
  if (!rows.length) return ''
  const cols = Array.from(rows.reduce((s, r) => { Object.keys(r).forEach(k => s.add(k)); return s }, new Set<string>()))
  return [cols.map(esc).join(','), ...rows.map(r => cols.map(c => esc(r[c])).join(','))].join('\r\n')
}
function save(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob), a = document.createElement('a')
  a.href = url; a.download = name; document.body.appendChild(a); a.click(); a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
export function downloadCsv(name: string, rows: Row[]) { save(new Blob(['﻿' + toCsv(rows)], { type: 'text/csv;charset=utf-8' }), name) }

export interface PdfSection { heading: string; rows?: [string, string | number][]; table?: Row[] }
export async function downloadPdf(name: string, title: string, subtitle: string, sections: PdfSection[]) {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight(), M = 48
  let y = M
  const ensure = (h: number) => { if (y + h > H - M) { doc.addPage(); y = M } }
  doc.setFillColor(8, 13, 24); doc.rect(0, 0, W, 78, 'F')
  doc.setTextColor(233, 240, 250); doc.setFont('helvetica', 'bold'); doc.setFontSize(18); doc.text('LINEZERO', M, 38)
  doc.setFontSize(10); doc.setTextColor(32, 214, 197); doc.text('Queue intelligence report', M, 56)
  y = 108; doc.setTextColor(20, 24, 40); doc.setFontSize(16); doc.text(title, M, y, { maxWidth: W - 2 * M }); y += 22
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(90, 100, 120); doc.text(subtitle, M, y, { maxWidth: W - 2 * M }); y += 26
  for (const s of sections) {
    ensure(40); doc.setFont('helvetica', 'bold'); doc.setFontSize(12); doc.setTextColor(60, 56, 200); doc.text(s.heading, M, y); y += 8
    doc.setDrawColor(210, 214, 230); doc.line(M, y, W - M, y); y += 16
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(30, 36, 54)
    for (const [k, v] of s.rows ?? []) { ensure(16); doc.setTextColor(100, 110, 130); doc.text(String(k), M, y); doc.setTextColor(20, 24, 40); doc.text(String(v), M + 190, y, { maxWidth: W - 2 * M - 190 }); y += 15 }
    if (s.table?.length) {
      const cols = Object.keys(s.table[0]), cw = (W - 2 * M) / cols.length
      ensure(18); doc.setFont('helvetica', 'bold'); cols.forEach((c, i) => doc.text(c, M + i * cw, y, { maxWidth: cw - 6 })); y += 14; doc.setFont('helvetica', 'normal')
      for (const r of s.table) { ensure(15); cols.forEach((c, i) => doc.text(String(r[c] ?? ''), M + i * cw, y, { maxWidth: cw - 6 })); y += 14 }
    }
    y += 14
  }
  const pages = doc.getNumberOfPages()
  for (let p = 1; p <= pages; p++) { doc.setPage(p); doc.setFontSize(8); doc.setTextColor(130, 138, 160); doc.text('Generated by LineZero · synthetic demo data unless stated otherwise', M, H - 24); doc.text(`${p} / ${pages}`, W - M, H - 24, { align: 'right' }) }
  save(doc.output('blob'), name)
}
